"""Do-nothing definitions of every function platform/gamespy.h declares (the GameSpy SDK's calls): headless there is
no online service. Each returns zero / null."""
import re, pathlib
src = (pathlib.Path.home() / "projects/thug2-decomp/src/platform/gamespy.h").read_text()
src = re.sub(r"//[^\n]*", "", src)
body = src[src.index("namespace game_spy {"):]
# drop the structs (their members aren't functions to define)
body = re.sub(r"struct \w+ \{.*?\n\};", "", body, flags=re.S)
out = ['// Generated by tools/gen_gamespy.py: the GameSpy calls, doing nothing (headless: no online service).',
       '#include "platform/gamespy.h"', '#include <cstdint>', 'namespace game_spy {']
for decl in re.findall(r"([^;{}]*?\([^;{}]*?\))\s*;", body, re.S):
    d = " ".join(decl.split()).replace("[[nodiscard]] ", "")
    if d.startswith(("using", "typedef", "namespace", "template", "return", "static_assert")) or "operator" in d or "=" in d.split("(")[0]:
        continue
    m = re.match(r"(.*?)\b(\w+)\s*\((.*)\)$", d)
    if not m:
        continue
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3)
    if not ret or ret in ("inline", "constexpr"):
        continue
    params = re.sub(r"\s*=\s*[^,)]+", "", params)
    out.append(f"{ret} {name}({params}) {{ {'' if ret == 'void' else 'return {};'} }}")
out.append("} // namespace game_spy")
print("\n".join(out))
