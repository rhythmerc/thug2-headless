"""Generates do-nothing implementations of the decomp's backend interfaces: every pure virtual of a class overridden
to return zero / null / "ok" (D3D's 0) with its out-parameters cleared. The harness derives from these and overrides
what must really work."""
import re, sys, pathlib
SRC = pathlib.Path.home() / "projects/thug2-decomp/src"

def pure_virtuals(header, cls):
    text = (SRC / header).read_text()
    m = re.search(r"\nclass %s\b[^{]*\{(.*?)\n\};" % re.escape(cls), text, re.S)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    decls = re.findall(r"virtual\s+([^;{]*?)\s*=\s*0\s*;", body, re.S)
    out = []
    for d in decls:
        d = " ".join(d.split())
        d = d.replace("[[nodiscard]] ", "")
        mm = re.match(r"(.*?)\b(\w+)\s*\((.*)\)\s*(const)?\s*$", d)
        ret, name, params, const = mm.group(1).strip(), mm.group(2), mm.group(3), mm.group(4)
        out.append((ret, name, params, const))
    return out

def split_params(params):
    depth, cur, parts = 0, "", []
    for ch in params:
        if ch in "<([": depth += 1
        if ch in ">)]": depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip()); cur = ""
        else:
            cur += ch
    if cur.strip(): parts.append(cur.strip())
    return parts

def emit(header, cls, name):
    lines = [f"class {name} : public {cls} {{", "public:"]
    for ret, fn, params, const in pure_virtuals(header, cls.split("::")[-1]):
        body = []
        for p in split_params(params):
            pm = re.match(r"(.*?)\b(\w+)$", p)
            if not pm: continue
            ptype, pname = pm.group(1).strip(), pm.group(2)
            if ptype.startswith("const"): continue
            if ptype.endswith("**"):
                body.append(f"if ({pname}) *{pname} = nullptr;")
            elif ptype.endswith("*") and ptype.rstrip("*").strip() in ("uint32_t", "int", "int32_t", "uint64_t", "long", "float", "bool"):
                body.append(f"if ({pname}) *{pname} = {{}};")
        if ret == "void":
            pass
        elif ret.endswith("&"):
            base = ret.rstrip("&").strip()
            body.append(f"static {base.replace('const ', '')} value{{}}; return value;")
        else:
            body.append("return {};")
        c = " const" if const else ""
        lines.append(f"    {ret} {fn}({params}){c} override {{ {' '.join(body)} }}")
    lines.append("};")
    return "\n".join(lines)

targets = [
    ("engine/gfx/gpu.h", "render::Gpu", "NullGpu"),
    ("engine/gfx/gpu_context.h", "render::GpuContext", "NullGpuContext"),
    ("engine/gfx/ui_backend.h", "render::UiBackend", "NullUiBackend"),
    ("engine/audio/audio_device.h", "audio::Device", "NullAudioDevice"),
    ("engine/media/movie.h", "media::Movie", "NullMovie"),
    ("engine/net/transport.h", "net::Transport", "NullTransport"),
]
print("// Generated by tools/gen_stubs.py: do-nothing implementations of the decomp's backend interfaces.")
print("#pragma once")
for h, _, _ in targets:
    print(f'#include "{h}"')
for h, c, n in targets:
    ns = c.split("::")[0]
    print(f"namespace {ns} {{")
    print(emit(h, c.split("::")[-1], n))
    print(f"}} // namespace {ns}")
    print()
